export type Translate = (key: MessageKey, values?: Record<string, string | number>) => string;

export function translate(locale: Locale, key: MessageKey, values: Record<string, string | number> = {}): string {
  let message: string = locale === "en" ? en[key] : zh[key];
  for (const [name, value] of Object.entries(values)) {
    message = message.replaceAll(`{${name}}`, String(value));
  }
  return message;
}

const I18nContext = createContext<{ locale: Locale; t: Translate }>({
  locale: "zh-CN",
  t: (key, values) => translate("zh-CN", key, values),
});

export function I18nProvider({ locale, children }: { locale: Locale; children: ReactNode }) {
  const value = useMemo(() => ({
    locale,
    t: (key: MessageKey, values?: Record<string, string | number>) => translate(locale, key, values),
  }), [locale]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  return useContext(I18nContext);
}
